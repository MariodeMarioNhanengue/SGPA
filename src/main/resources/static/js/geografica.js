// ================================================================
//  FUNÇÃO REUTILIZÁVEL — inicializa os selects de uma vez dada a ID
// ================================================================
function inicializarGeo(idProvincia, idDistrito, idBairro, valorProvincia, valorDistrito, valorBairro) {
  const selProvincia = document.getElementById(idProvincia);
  const selDistrito  = document.getElementById(idDistrito);
  const selBairro    = document.getElementById(idBairro);

  if (!selProvincia || !selDistrito || !selBairro) return; // elementos não existem ainda

  // Preencher províncias
  Object.keys(GEO).sort().forEach(prov => {
    const opt = document.createElement('option');
    opt.value = prov;
    opt.textContent = prov;
    selProvincia.appendChild(opt);
  });

  // Ao mudar a Província → preencher Distritos
  selProvincia.addEventListener('change', function () {
    const prov = this.value;
    selDistrito.innerHTML = '<option value="">Selecione o distrito...</option>';
    selDistrito.disabled = true;
    selBairro.innerHTML   = '<option value="">Selecione o bairro...</option>';
    selBairro.disabled    = true;
    if (!prov || !GEO[prov]) return;
    Object.keys(GEO[prov]).sort().forEach(dist => {
      const opt = document.createElement('option');
      opt.value = dist;
      opt.textContent = dist;
      selDistrito.appendChild(opt);
    });
    selDistrito.disabled = false;
  });

  // Ao mudar o Distrito → preencher Bairros
  selDistrito.addEventListener('change', function () {
    const prov = selProvincia.value;
    const dist = this.value;
    selBairro.innerHTML = '<option value="">Selecione o bairro...</option>';
    selBairro.disabled  = true;
    if (!prov || !dist || !GEO[prov] || !GEO[prov][dist]) return;
    const bairros = GEO[prov][dist];
    if (!bairros || bairros.length === 0) {
      selBairro.innerHTML = '<option value="">Sem bairros registados</option>';
      return;
    }
    bairros.sort().forEach(b => {
      const opt = document.createElement('option');
      opt.value = b;
      opt.textContent = b;
      selBairro.appendChild(opt);
    });
    selBairro.disabled = false;
  });

  // Pré-selecionar valores existentes (para edição de perfil)
  if (valorProvincia) {
    for (let i = 0; i < selProvincia.options.length; i++) {
      if (selProvincia.options[i].value === valorProvincia || selProvincia.options[i].text === valorProvincia) {
        selProvincia.selectedIndex = i;
        selProvincia.dispatchEvent(new Event('change'));
        break;
      }
    }
    if (valorDistrito) {
      setTimeout(function () {
        for (let i = 0; i < selDistrito.options.length; i++) {
          if (selDistrito.options[i].value === valorDistrito || selDistrito.options[i].text === valorDistrito) {
            selDistrito.selectedIndex = i;
            selDistrito.dispatchEvent(new Event('change'));
            break;
          }
        }
        if (valorBairro) {
          setTimeout(function () {
            for (let i = 0; i < selBairro.options.length; i++) {
              if (selBairro.options[i].value === valorBairro || selBairro.options[i].text === valorBairro) {
                selBairro.selectedIndex = i;
                break;
              }
            }
          }, 200);
        }
      }, 200);
    }
  }
}

// ================================================================
//  INICIALIZAÇÃO AUTOMÁTICA ao carregar o DOM
//  — funciona para páginas que já têm os selects visíveis (editar-perfil, criar-produtor, etc.)
//  — NÃO inicializa se os elementos não existirem ainda (criar-comprador step2)
// ================================================================
document.addEventListener('DOMContentLoaded', function () {
  if (document.getElementById('provinciaC')) {
    const vP = document.getElementById('currentProvincia')?.value || '';
    const vD = document.getElementById('currentDistrito')?.value  || '';
    const vB = document.getElementById('currentBairro')?.value    || '';
    inicializarGeo('provinciaC', 'distritoC', 'bairroC', vP, vD, vB);
  }
});
