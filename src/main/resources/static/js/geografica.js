  const selProvincia = document.getElementById('provinciaC');
  const selDistrito  = document.getElementById('distritoC');
  const selBairro    = document.getElementById('bairroC');

  // Preencher províncias ao carregar
  Object.keys(GEO).sort().forEach(prov => {
    const opt = document.createElement('option');
    opt.value = prov;
    opt.textContent = prov;
    selProvincia.appendChild(opt);
  });

  // Ao mudar a Província → preencher Distritos
  selProvincia.addEventListener('change', function () {
    const prov = this.value;

    selDistrito.innerHTML = '<option value="">Selecione o distrito...</option>';
    selDistrito.disabled = true;
    selBairro.innerHTML   = '<option value="">Selecione o distrito...</option>';
    selBairro.disabled    = true;

    if (!prov || !GEO[prov]) return;

    Object.keys(GEO[prov]).sort().forEach(dist => {
      const opt = document.createElement('option');
      opt.value = dist;
      opt.textContent = dist;
      selDistrito.appendChild(opt);
    });
    selDistrito.disabled = false;
  });

  // Ao mudar o Distrito → preencher Bairros
  selDistrito.addEventListener('change', function () {
    const prov = selProvincia.value;
    const dist = this.value;

    selBairro.innerHTML = '<option value="">Selecione o bairro...</option>';
    selBairro.disabled  = true;

    if (!prov || !dist || !GEO[prov] || !GEO[prov][dist]) return;

    const bairros = GEO[prov][dist];
    if (!bairros || bairros.length === 0) {
      selBairro.innerHTML = '<option value="">Sem bairros registados</option>';
      return;
    }

    bairros.sort().forEach(b => {
      const opt = document.createElement('option');
      opt.value = b;
      opt.textContent = b;
      selBairro.appendChild(opt);
    });
    selBairro.disabled = false;
  });
